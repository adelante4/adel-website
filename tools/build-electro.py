#!/usr/bin/env python3
"""Builds the electronic drum kits (808 and 909 style) as sampled kits, the way the machines made them: by synthesis.

Usage: python3 tools/build-electro.py [kit ...]
Nothing is sampled from a commercial machine: every sound is generated here from oscillators, noise and filters,
so the result is original. Output goes to assets/audio/kits/<id>/ in the same format the sampler reads for any kit
(three velocity layers, two round robins, 16-bit mono 44.1 kHz WAV, manifest).
"""
import glob, json, os, sys, zlib
import numpy as np
import scipy.io.wavfile as wav
from scipy.signal import butter, sosfilt

SR = 44100
OUT = os.path.join(os.path.dirname(__file__), "..", "assets", "audio", "kits")
T = lambda s: np.arange(int(s * SR)) / SR


def filt(x, kind, freq, order=2):
    return sosfilt(butter(order, freq, btype=kind, fs=SR, output="sos"), x)


def env(t, decay, attack=0.0015):
    e = np.exp(-t / decay)
    if attack:
        e *= np.minimum(1, t / attack)
    return e


def sweep(t, f0, f1, tau):
    """A sine whose pitch falls from f0 to f1 (time constant tau): the heart of a kick or a tom."""
    f = f1 + (f0 - f1) * np.exp(-t / tau)
    return np.sin(2 * np.pi * np.cumsum(f) / SR)


def squares(t, freqs):
    return sum(np.sign(np.sin(2 * np.pi * f * t)) for f in freqs) / len(freqs)


def kick808(v, rr, rng):
    t = T(1.3)
    body = sweep(t, 150 + 40 * v, 46, 0.03 + 0.01 * v) * env(t, 0.55 + 0.25 * v, 0.001)
    click = filt(rng.standard_normal(len(t)), "bandpass", [1500, 5000]) * env(t, 0.004, 0) * (0.1 + 0.25 * v)
    return np.tanh(body * (1.3 + 1.2 * v)) + click


def kick909(v, rr, rng):
    t = T(0.6)
    body = sweep(t, 230 + 60 * v, 54, 0.02) * env(t, 0.22 + 0.1 * v, 0.0008)
    click = filt(rng.standard_normal(len(t)), "highpass", 2500) * env(t, 0.006, 0) * (0.2 + 0.4 * v)
    return np.tanh(body * (2.0 + 2.0 * v)) + click


def snare808(v, rr, rng):
    t = T(0.45)
    tone = (np.sin(2 * np.pi * 180 * t) * env(t, 0.07) + np.sin(2 * np.pi * 330 * t) * env(t, 0.05)) * 0.8
    noise = filt(rng.standard_normal(len(t)), "highpass", 1800) * env(t, 0.13 + 0.05 * v, 0.0008)
    return tone * (0.7 + 0.3 * v) + noise * (0.55 + 0.35 * v)


def snare909(v, rr, rng):
    t = T(0.5)
    tone = (np.sin(2 * np.pi * (170 + 30 * v) * t) * env(t, 0.05) + np.sin(2 * np.pi * 330 * t) * env(t, 0.035)) * 0.7
    noise = filt(rng.standard_normal(len(t)), "highpass", 1200) * env(t, 0.17 + 0.05 * v, 0.0006)
    return np.tanh((tone * (0.6 + 0.3 * v) + noise * (0.7 + 0.4 * v)) * 1.4)


def clap(v, rr, rng, bursts=4, tail=0.18):
    t = T(0.5)
    n = filt(rng.standard_normal(len(t)), "bandpass", [900, 2600], 2)
    e = env(t, tail, 0.001) * 0.6
    for i in range(bursts - 1):
        s = i * 0.011
        e += np.where((t > s) & (t < s + 0.009), np.exp(-(t - s) / 0.003), 0) * 1.0
    return n * e * (0.6 + 0.5 * v)


def rim808(v, rr, rng):
    t = T(0.2)
    x = (np.sin(2 * np.pi * 455 * t) + np.sin(2 * np.pi * 1667 * t) * 0.8) * env(t, 0.008, 0.0003)
    x += filt(rng.standard_normal(len(t)), "bandpass", [3000, 7000]) * env(t, 0.006, 0) * 0.3
    return np.tanh(x * (1.2 + v))


def hat(freqs, hp, decay, length, v, rng, lp=16000):
    t = T(length)
    x = squares(t, freqs) + 0.25 * rng.standard_normal(len(t))
    x = filt(filt(x, "bandpass", [6500, lp], 2), "highpass", hp)
    return x * env(t, decay, 0.0004) * (0.5 + 0.5 * v)


F808 = [205.3, 304.4, 369.6, 522.7, 540.0, 800.0]
F909 = [263.0, 400.0, 421.0, 474.0, 587.0, 845.0]


def cowbell(v, rr, rng):
    t = T(0.5)
    x = (np.sign(np.sin(2 * np.pi * 540 * t)) + np.sign(np.sin(2 * np.pi * 800 * t))) * 0.5
    x = filt(x, "bandpass", [500, 2600], 2)
    return x * (env(t, 0.06, 0.0005) * 0.8 + env(t, 0.22, 0.0005) * 0.3) * (0.5 + 0.5 * v)


def ride909(v, rr, rng):
    t = T(1.4)
    x = squares(t, [380, 561, 668, 801, 1024, 1303]) + 0.15 * rng.standard_normal(len(t))
    x = filt(x, "highpass", 4500)
    return x * (env(t, 0.5, 0.0005) * 0.7 + env(t, 0.08, 0.0005) * 0.5) * (0.5 + 0.5 * v)


def write(kit_id, name, credit, voices):
    d = os.path.join(OUT, kit_id)
    os.makedirs(d, exist_ok=True)
    for f in glob.glob(os.path.join(d, "*")):
        os.remove(f)
    man = {"id": kit_id, "name": name, "license": "Original, generated by tools/build-electro.py", "credit": credit, "sampleRate": SR, "voices": {}}
    for voice, (fn, layers, peak, length_cut, fade) in voices.items():
        hits, raw = [], []
        for li in range(layers):
            v = (li + 0.5) / layers
            for ri in range(2):
                rng = np.random.default_rng(zlib.crc32(f"{kit_id}{voice}{li}{ri}".encode()))
                raw.append((li, fn(v, ri, rng), 0.35 + 0.65 * v))  # softer layers are quieter
        top = max(np.abs(x).max() * a for _, x, a in raw)
        scale = 10 ** (peak / 20) / top
        for k, (li, x, a) in enumerate(raw):
            x = x[: int(length_cut * SR)].copy()
            f = min(len(x), int(fade * SR))
            x[-f:] *= np.linspace(1, 0, f) ** 2
            name_ = f"{voice}-{li}-{k % 2 + 1}.wav"
            wav.write(os.path.join(d, name_), SR, (np.clip(x * a * scale, -1, 1) * 32767).astype(np.int16))
            hits.append({"layer": li, "file": name_})
        man["voices"][voice] = {"layers": layers, "hits": hits}
    json.dump(man, open(os.path.join(d, "manifest.json"), "w"), indent=1)
    size = sum(os.path.getsize(f) for f in glob.glob(os.path.join(d, "*")))
    print(f"{kit_id}: {len(man['voices'])} voices, {size / 1e6:.2f} MB")


def main():
    want = set(sys.argv[1:])
    kits = {
        "tr808": (
            "808 machine",
            "Generated: long sine-sweep kick, tuned-tone snare, clap, metallic hats, cowbell",
            {
                "kick": (kick808, 3, -2, 1.2, 0.3),
                "snare": (snare808, 3, -3, 0.4, 0.1),
                "ghost": (lambda v, r, g: clap(v, r, g, 3, 0.1), 2, -14, 0.3, 0.1),
                "rim": (rim808, 2, -8, 0.2, 0.05),
                "hat": (lambda v, r, g: hat(F808, 7000, 0.03, 0.15, v, g), 3, -9, 0.15, 0.04),
                "ohat": (lambda v, r, g: hat(F808, 6500, 0.22, 0.8, v, g), 2, -9, 0.8, 0.3),
                "foot": (lambda v, r, g: hat(F808, 7500, 0.018, 0.1, v, g), 2, -12, 0.1, 0.03),
                "ride": (cowbell, 3, -8, 0.5, 0.15),
            },
        ),
        "tr909": (
            "909 machine",
            "Generated: punchy kick, snappy snare, four-burst clap, bright hats, noise ride",
            {
                "kick": (kick909, 3, -2, 0.55, 0.15),
                "snare": (snare909, 3, -3, 0.45, 0.1),
                "ghost": (lambda v, r, g: clap(v, r, g, 4, 0.12), 2, -14, 0.3, 0.1),
                "rim": (lambda v, r, g: rim808(v, r, g) * 1.0, 2, -8, 0.2, 0.05),
                "hat": (lambda v, r, g: hat(F909, 7500, 0.04, 0.2, v, g), 3, -9, 0.2, 0.05),
                "ohat": (lambda v, r, g: hat(F909, 7000, 0.3, 1.0, v, g), 2, -9, 1.0, 0.4),
                "foot": (lambda v, r, g: hat(F909, 8000, 0.025, 0.12, v, g), 2, -12, 0.12, 0.04),
                "ride": (ride909, 3, -9, 1.4, 0.5),
            },
        ),
    }
    for k, (name, credit, voices) in kits.items():
        if not want or k in want:
            write(k, name, credit, voices)


if __name__ == "__main__":
    main()
